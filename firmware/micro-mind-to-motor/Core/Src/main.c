/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */
  static const uint8_t identity[] = "I mind2motor 1\r\n";
  uint8_t received_byte = 0U;
  char rx_line[RX_LINE_CAPACITY];
  uint8_t rx_length = 0U;
  uint8_t rx_spoiled = 0U;
  uint8_t left_percent = 0U;
  uint8_t right_percent = 0U;
  uint8_t link_live = 0U;
  uint32_t rejected = 0U;
  uint32_t last_command_tick = 0U;
  uint32_t last_status_tick = 0U;
  char status_message[48];
  /* USER CODE END 1 */

  /* MPU Configuration--------------------------------------------------------*/
  MPU_Config();

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_ADC1_Init();
  MX_TIM1_Init();
  MX_TIM3_Init();
  MX_TIM4_Init();
  MX_ADC2_Init();
  MX_USART1_UART_Init();
  /* USER CODE BEGIN 2 */
  /* Keep both motor drivers asleep until a valid Bluetooth wheel frame. */
  HAL_GPIO_WritePin(NSLEEP_HB_1_GPIO_Port, NSLEEP_HB_1_Pin, GPIO_PIN_RESET);
  HAL_GPIO_WritePin(NSLEEP_HB_2_GPIO_Port, NSLEEP_HB_2_Pin, GPIO_PIN_RESET);

  /* Start PWM with every input at 0% duty, then keep both drivers asleep. */
  if (HAL_TIM_PWM_Start(&htim4, MO1_IN1) != HAL_OK ||
      HAL_TIM_PWM_Start(&htim4, MO1_IN2) != HAL_OK ||
      HAL_TIM_PWM_Start(&htim4, MO2_IN1) != HAL_OK ||
      HAL_TIM_PWM_Start(&htim4, MO2_IN2) != HAL_OK)
  {
    Error_Handler();
  }

  Motors_Stop();
  HAL_UART_Transmit(&huart1, (uint8_t *)identity,
                    sizeof(identity) - 1U, 100U);
  last_status_tick = HAL_GetTick();
  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
    HAL_StatusTypeDef receive_status =
        HAL_UART_Receive(&huart1, &received_byte, 1U, 5U);

    if (receive_status == HAL_OK)
    {
      if (received_byte == '\n')
      {
        if (rx_spoiled != 0U)
        {
          rejected++;
        }
        else if (rx_length == 1U && rx_line[0] == '?')
        {
          HAL_UART_Transmit(&huart1, (uint8_t *)identity,
                            sizeof(identity) - 1U, 100U);
        }
        else if (rx_length != 0U &&
                 Parse_Wheel_Command(rx_line, rx_length,
                                     &left_percent, &right_percent) != 0U)
        {
          Motors_SetWheelPercent(left_percent, right_percent);
          last_command_tick = HAL_GetTick();
          link_live = 1U;
        }
        else if (rx_length != 0U)
        {
          rejected++;
        }
        rx_length = 0U;
        rx_spoiled = 0U;
      }
      else if (received_byte == '\r')
      {
        /* Accept CRLF as well as LF. */
      }
      else if (rx_length < sizeof(rx_line))
      {
        rx_line[rx_length++] = (char)received_byte;
      }
      else
      {
        rx_spoiled = 1U;
      }
    }
    else if (receive_status != HAL_TIMEOUT)
    {
      rx_length = 0U;
      rx_spoiled = 0U;
      rejected++;
      __HAL_UART_CLEAR_OREFLAG(&huart1);
    }

    uint32_t now = HAL_GetTick();
    if (link_live != 0U && now - last_command_tick > LINK_TIMEOUT_MS)
    {
      Motors_Stop();
      left_percent = 0U;
      right_percent = 0U;
      link_live = 0U;
    }

    if (now - last_status_tick >= STATUS_PERIOD_MS)
    {
      int length = snprintf(status_message, sizeof(status_message),
                            "S %s %u %u %lu\r\n",
                            link_live != 0U ? "pc" : "idle",
                            (unsigned int)left_percent,
                            (unsigned int)right_percent,
                            (unsigned long)rejected);
      if (length > 0)
      {
        HAL_UART_Transmit(&huart1, (uint8_t *)status_message,
                          (uint16_t)length, 100U);
      }
      last_status_tick = now;
    }
  }
  /* USER CODE END 3 */
}

